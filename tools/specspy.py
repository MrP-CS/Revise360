"""The Python course - thirteen 360 experiences, one per lesson.

This is not a specification topic. It sits beyond OCR J277 as topic "PY", so a
teacher can teach programming and track progress through it without it being
mistaken for 2.2 Programming techniques, which it is closely related to but not
a substitute for.

The practice tasks on every station are the verified code questions from
tools/codebank/pr-lNN.json. They are read at import time and turned into task
dicts here, so the bank stays the single source of truth: nothing about a
question - its wording, its brief, its tests or its marks - is retyped in this
file. The six station names also come from the bank, in the bank's order, so a
station can never drift away from the questions sitting on it.
"""
import os, json
from kit import mcq, multi, sort, match, order

KPY = "Python programming"
SUBPY = "Revise 360 Python course  |  Beyond the OCR J277 specification"

BANK = os.path.join(os.path.dirname(os.path.abspath(__file__)), "codebank")
_LOADED = {}


def _bank(lesson):
    if lesson not in _LOADED:
        with open(os.path.join(BANK, lesson + ".json"), encoding="utf-8") as fh:
            _LOADED[lesson] = json.load(fh)
    return _LOADED[lesson]


def code_tasks(lesson, station):
    """The bank's questions for one station, as player tasks.

    `id` and `station` are bank bookkeeping and are left behind. Model
    solutions are not in the bank at all - they live in answers/, which git
    ignores - so none can reach a file the browser downloads.
    """
    out = []
    for q in _bank(lesson)["questions"]:
        if q["station"] != station:
            continue
        t = dict(t="code", marks=q["marks"], q=q["q"], brief=q["brief"], fb=q["fb"])
        # Which stage of the release this is: try, predict, change, complete,
        # debug or build. The player shows it to the pupil in words, because a
        # task to be run is read differently from one to be written.
        if q.get("kind") and q["kind"] != "build":
            t["kind"] = q["kind"]
        # A predict activity has no editor: the program is fixed and the answer
        # is chosen from a list, correct one first.
        if q.get("kind") == "predict":
            t["code"] = q["code"]
            t["a"] = q["a"]
            if q.get("in"):
                t["in"] = q["in"]
        else:
            t["starter"] = q["starter"]
            t["tests"] = q.get("tests") or []
            if q.get("in"):
                t["in"] = q["in"]
        # An optional stretch activity. It is offered, never required, and it
        # does not count against a pupil who leaves it.
        if q.get("opt"):
            t["opt"] = True
        # The hint: either a diagram name on its own, or a ladder of rungs
        # (think, syntax, start, walk, diagram) revealed one press at a time.
        if q.get("hint"):
            t["hint"] = q["hint"]
        # The worked example shown above the task, where the question carries one
        if q.get("teach"):
            t["teach"] = q["teach"]
        # A plain-English sentence for each line of that example, folded away
        if q.get("lines"):
            t["lines"] = q["lines"]
        if q.get("forbid"):
            t["forbid"] = q["forbid"]
        if q.get("require"):
            t["require"] = q["require"]
        out.append(t)
    if not out:
        raise ValueError(f"{lesson} station {station} has no questions in the bank")
    return out


def stn(lesson, i, bullets, challenge, ill, fact):
    """One station: its name and its tasks come from the bank, the rest is teaching."""
    return dict(name=_bank(lesson)["stations"][i], bullets=bullets,
                challenge=challenge, ill=ill, fact=fact, tasks=code_tasks(lesson, i))


